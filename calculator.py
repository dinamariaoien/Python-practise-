def multiply(a, b):
    """Multiply two numbers."""
    return a * b


def add(a, b):
    """Add two numbers."""
    return a + b


def subtract(a, b):
    """Subtract one number from another."""
    return a - b


def divide(a, b):
    """Divide one number by another."""
    return a / b

if __name__ == "__main__":
    print(add(10, 5))
    print(subtract(10, 5))
    print(multiply(10, 5))
    print(divide(10, 5))